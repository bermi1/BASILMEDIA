// Regenerates supabase/migrations/0003_seed_public_content.sql from src/lib/seed.ts.
// Usage: npm run seed:sql
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const out = await build({ entryPoints: ['src/lib/seed.ts'], bundle: true, format: 'esm', platform: 'node', write: false });
const mod = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`);
const { SEED, DEFAULT_SETTINGS } = mod;

const lit = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rows = (table, list, skip = ['id']) => {
  if (!list.length) return '';
  const cols = Object.keys(list[0]).filter((c) => !skip.includes(c));
  return `insert into public.${table} (${cols.join(', ')}) values\n${list.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')};\n\n`;
};

let sql = '-- Basil Media OS · 0003 starter content (generated by scripts/gen-seed-sql.mjs — edit seed.ts, not this file).\n-- Everything here is editable in the Website CMS.\n\n';
// hero_images and office_hours are added (and filled) by migration 0010.
sql += rows('site_settings', [{ ...DEFAULT_SETTINGS }], ['hero_images', 'office_hours']);
for (const t of ['services', 'projects_public', 'partners', 'highlights', 'team', 'testimonials', 'news_stories', 'opportunities', 'events']) sql += rows(t, SEED[t]);
const g = SEED.galleries[0];
sql += `with g as (\n${rows('galleries', [g]).trim().replace(/;$/, '')}\n  returning id\n)\n`;
const m = SEED.media_items.map(({ id, gallery_id, ...r }) => r);
const cols = Object.keys(m[0]);
sql += `insert into public.media_items (gallery_id, ${cols.join(', ')})\nselect g.id, v.* from g, (values\n${m.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')}\n) as v(${cols.join(', ')});\n`;
writeFileSync('supabase/migrations/0003_seed_public_content.sql', sql);
console.log('wrote supabase/migrations/0003_seed_public_content.sql');
